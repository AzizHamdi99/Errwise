import type { Event, Issue } from '@prisma/client';

const TITLE_PREFIX = '[Errwise] ';
const MAX_TITLE_LENGTH = 200; // GitHub allows 256
const MAX_MESSAGE_CHARS = 1_000;
const MAX_STACK_CHARS = 4_000;
const MAX_CELL_CHARS = 100;
const WRAP_COLUMNS = 100;
const MAX_LABEL_CHARS = 50; // GitHub's limit for a label name
// GitHub rejects a body over 65 536 characters. Every part is capped already, this is the net.
const MAX_BODY_CHARS = 60_000;
const MAX_SOURCE_FILES = 5;

export interface GithubIssueContent {
  title: string;
  body: string;
  labels: string[];
}

/**
 * The part of a stored analysis the issue needs. Structural on purpose: the content builder
 * stays a pure function, and a row stored before prompt v4 (no title, no steps) still fits.
 */
export interface GithubIssueAnalysis {
  summary: string;
  probableCause: string;
  suggestedFix: string;
  confidence: string;
  model: string;
  createdAt: Date;
  issueTitle?: string;
  reproSteps?: string[];
  sourceFiles?: string[];
}

interface BuildInput {
  issue: Issue;
  event: Event | null;
  issueUrl: string;
  analysis?: GithubIssueAnalysis | null;
}

export function buildGithubIssueContent({
  issue,
  event,
  issueUrl,
  analysis = null,
}: BuildInput): GithubIssueContent {
  const rows: [string, string][] = [
    ['Status', issue.status],
    ['Level', issue.level],
    ['Environment', event?.environment ?? 'unknown'],
    ['Release', event?.release ?? issue.lastRelease ?? 'unknown'],
    ['Occurrences', String(issue.eventCount)],
    ['First seen', issue.firstSeenAt.toISOString()],
    ['Last seen', issue.lastSeenAt.toISOString()],
  ];

  const sections = [
    `**[View in Errwise](${issueUrl})**`,
    [
      '| | |',
      '|---|---|',
      ...rows.map(([label, value]) => `| ${label} | ${cell(value)} |`),
    ].join('\n'),
  ];

  if (analysis) sections.push(...analysisSections(analysis));

  if (event) {
    sections.push(
      '### Message',
      codeBlock(truncate(event.message, MAX_MESSAGE_CHARS)),
    );
    if (event.stack) {
      sections.push(
        '### Stack trace',
        codeBlock(truncate(event.stack, MAX_STACK_CHARS)),
      );
    }
  }
  sections.push('---', '_Created from Errwise_');

  return {
    title: buildTitle(issue, analysis),
    body: truncate(sections.join('\n\n'), MAX_BODY_CHARS),
    labels: buildLabels(issue, event),
  };
}

function analysisSections(analysis: GithubIssueAnalysis): string[] {
  const sections = [
    '### AI analysis',
    `Generated by ${cell(analysis.model)} on ${analysis.createdAt.toISOString().slice(0, 10)}, confidence ${cell(analysis.confidence)}. It can be wrong: check it before acting on it.`,
    '**Summary**',
    modelText(analysis.summary),
    '**Probable cause**',
    modelText(analysis.probableCause),
    '**Suggested fix**',
    modelText(analysis.suggestedFix),
  ];

  const steps = analysis.reproSteps ?? [];
  if (steps.length > 0) {
    sections.push(
      '**Steps to reproduce (a guess)**',
      modelText(steps.map((step, i) => numbered(i + 1, step)).join('\n')),
    );
  }

  const files = (analysis.sourceFiles ?? []).slice(0, MAX_SOURCE_FILES);
  if (files.length > 0) {
    sections.push(`**Code read:** ${files.map(cell).join(', ')}`);
  }
  return sections;
}

/** Model output is untrusted: a plain-text fence is the only place it is shown. */
function modelText(text: string): string {
  return codeBlock(wrap(stripControl(text), WRAP_COLUMNS), 'text');
}

function numbered(n: number, step: string): string {
  const prefix = `${n}. `;
  const lines = wrap(stripControl(step), WRAP_COLUMNS - prefix.length).split(
    '\n',
  );
  const indent = ' '.repeat(prefix.length);
  return lines.map((line, i) => (i === 0 ? prefix : indent) + line).join('\n');
}

/** Titles are not markdown, but a newline or control character would still be odd. */
function buildTitle(issue: Issue, analysis: GithubIssueAnalysis | null) {
  const wanted = oneLine(analysis?.issueTitle ?? '') || oneLine(issue.title);
  return truncate(`${TITLE_PREFIX}${wanted}`, MAX_TITLE_LENGTH);
}

/**
 * A fixed, small set. `level` and `environment` come from the SDK, so they are cleaned and
 * capped before they become label names.
 */
function buildLabels(issue: Issue, event: Event | null): string[] {
  const candidates = [
    'errwise',
    'bug',
    labelFor('level', issue.level),
    labelFor('env', event?.environment),
  ];
  return [...new Set(candidates.filter((l): l is string => l !== null))];
}

function labelFor(prefix: string, value: string | null | undefined) {
  const cleaned = (value ?? '')
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return cleaned ? `${prefix}:${cleaned}`.slice(0, MAX_LABEL_CHARS) : null;
}

export function truncate(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

export function oneLine(text: string): string {
  return stripControl(text).replace(/\s+/g, ' ').trim();
}

/** Keeps newlines and tabs, drops the rest of the control characters (and CR). */
export function stripControl(text: string): string {
  return (
    text
      .replace(/\r/g, '')
      // eslint-disable-next-line no-control-regex
      .replace(/[\u0000-\u0008\u000b-\u001f\u007f]/g, '')
  );
}

/** Breaks lines at spaces. A word longer than a line is cut, so no line is unbounded. */
export function wrap(text: string, columns: number): string {
  return text
    .split('\n')
    .map((line) => wrapLine(line, columns))
    .join('\n');
}

function wrapLine(line: string, columns: number): string {
  if (line.length <= columns) return line;
  const out: string[] = [];
  let current = '';
  for (const word of line.split(' ')) {
    let rest = word;
    while (rest.length > columns) {
      if (current) {
        out.push(current);
        current = '';
      }
      out.push(rest.slice(0, columns));
      rest = rest.slice(columns);
    }
    if (!current) current = rest;
    else if (current.length + 1 + rest.length <= columns) {
      current += ` ${rest}`;
    } else {
      out.push(current);
      current = rest;
    }
  }
  if (current) out.push(current);
  return out.join('\n');
}

/** Inline code keeps SDK-provided values from becoming markdown or @mentions. */
export function cell(value: string): string {
  return `\`${value.replace(/[`|\r\n]+/g, ' ').slice(0, MAX_CELL_CHARS)}\``;
}

/** The fence is longer than any backtick run inside, so the text cannot break out. */
export function codeBlock(text: string, language = ''): string {
  const runs: string[] = text.match(/`+/g) ?? [];
  const longestRun = runs.reduce((max, run) => Math.max(max, run.length), 0);
  const fence = '`'.repeat(Math.max(3, longestRun + 1));
  return `${fence}${language}\n${text}\n${fence}`;
}
