import type { FixSuggestion, FixWarning } from '@errwise/shared';
import {
  cell,
  codeBlock,
  oneLine,
  stripControl,
  truncate,
  wrap,
} from '../github/github-issue-content';

const TITLE_PREFIX = '[Errwise] ';
const MAX_TITLE_LENGTH = 120;
const WRAP_COLUMNS = 100;
const MAX_BODY_CHARS = 60_000; // GitHub rejects a body over 65 536 characters
const MAX_LISTED_FILES = 10;

/** Our own wording for what a patch adds: the model and the code never write these lines. */
const WARNING_TEXT: Record<FixWarning, string> = {
  reads_environment: 'The change reads environment variables.',
  runs_shell_command: 'The change runs a shell command.',
  makes_network_call: 'The change makes a network call.',
  adds_import: 'The change adds an import or a require.',
  evaluates_code: 'The change evaluates code at run time.',
};

export interface PullRequestInput {
  suggestion: FixSuggestion;
  /** Built by the backend: the one real link of the body. */
  issueUrl: string;
  /** Only for a GitHub issue of this same repository, see `linkedGithubIssue`. */
  githubIssueNumber: number | null;
  /** The files the change touches, as repository paths. */
  files: string[];
}

export interface PullRequestContent {
  title: string;
  body: string;
  commitMessage: string;
}

/**
 * The text of the pull request. Pure, like the one of the GitHub issue (ADR-004): model text
 * only goes in a fenced `text` block or in the title with `#` and `@` removed, so nothing in
 * it can ping someone, link an issue or break out. The commit message has none of it.
 */
export function buildPullRequestContent(
  input: PullRequestInput,
): PullRequestContent {
  const { suggestion, issueUrl, githubIssueNumber, files } = input;

  const listed = files.slice(0, MAX_LISTED_FILES).map(cell).join(', ');
  const more =
    files.length > MAX_LISTED_FILES
      ? ` and ${files.length - MAX_LISTED_FILES} more`
      : '';

  const sections = [
    `**[View the error in Errwise](${issueUrl})**`,
    [
      'This change was suggested by an AI and has not been run by Errwise or by your tests. Read it like any other pull request, and check that CI passes before you merge.',
    ].join(' '),
    [
      '| | |',
      '|---|---|',
      `| Confidence | ${cell(suggestion.confidence)} |`,
      `| Model | ${cell(suggestion.model)} |`,
      `| Files | ${listed}${more} |`,
    ].join('\n'),
    '### What was wrong, and what this changes',
    codeBlock(wrap(stripControl(suggestion.explanation), WRAP_COLUMNS), 'text'),
  ];

  if (suggestion.warnings.length > 0) {
    sections.push(
      '### Worth a second look',
      suggestion.warnings.map((w) => `- ${WARNING_TEXT[w]}`).join('\n'),
    );
  }

  // The one keyword: merging closes the GitHub issue, and the webhook resolves the Errwise one.
  if (githubIssueNumber !== null) sections.push(`Fixes #${githubIssueNumber}`);
  sections.push('---', '_Opened from Errwise as a draft._');

  return {
    title: buildTitle(suggestion.prTitle),
    body: truncate(sections.join('\n\n'), MAX_BODY_CHARS),
    commitMessage: [
      'Apply an AI-suggested fix from Errwise',
      '',
      'Generated by Errwise and not run by it. Review before merging.',
      `Errwise issue: ${issueUrl}`,
    ].join('\n'),
  };
}

/** Plain text on one line, without what GitHub turns into a link or a mention. */
function buildTitle(modelTitle: string): string {
  const cleaned = oneLine(modelTitle)
    .replace(/[#@`<>]/g, '')
    .trim();
  return truncate(
    `${TITLE_PREFIX}${cleaned || 'Suggested fix'}`,
    MAX_TITLE_LENGTH,
  );
}

/**
 * The number of the GitHub issue made from this Errwise issue, if it belongs to `repo`. The
 * stored number alone is not enough: if the project was connected to another repository since,
 * "#12" could be an unrelated issue there, and merging would close it.
 */
export function linkedGithubIssue(
  issue: { githubIssueNumber: number | null; githubIssueUrl: string | null },
  repo: string,
): number | null {
  const { githubIssueNumber: number, githubIssueUrl: url } = issue;
  if (number === null || !url) return null;
  const expected = `https://github.com/${repo}/issues/${number}`;
  return url.toLowerCase() === expected.toLowerCase() ? number : null;
}
